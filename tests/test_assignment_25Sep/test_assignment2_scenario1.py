# Application: ParaBank Demo Banking Application
# URL: https://parabank.parasoft.com/parabank/index.htm
# Scenario 1: User Registration & Account Verification
from playwright.sync_api import sync_playwright, expect
PARABANK_URL = "https://parabank.parasoft.com/parabank/index.htm"
USERNAME = "testuser_987654"
PASSWORD = "Test@12345"
def test_parabank_registration_and_account():
    with sync_playwright() as p:
        browser = p.chromium.launch(headless=False)
        page = browser.new_page(viewport={"width": 1440,"height": 900})
        print()
        print("Open ParaBank")
        page.goto(PARABANK_URL,wait_until="domcontentloaded",timeout=30000)
        print("URL:", page.url)
        expect(page.locator("body")).to_contain_text("ParaBank",timeout=15000)
        print("Navigate to Register page")
        register_link = page.get_by_role("link", name="Register")
        expect(register_link).to_be_visible(timeout=15000)
        register_link.click()
        page.wait_for_load_state("domcontentloaded",timeout=30000)
        print("Register page URL:", page.url)
        expect( page.locator("body")).to_contain_text("Signing up is easy!",timeout=15000)
        print("Enter customer details")
        page.locator("input[name='customer.firstName']").fill("shincy")
        page.locator("input[name='customer.lastName']").fill("rose")
        page.locator("input[name='customer.address.street']").fill("123 benxy street")
        page.locator("input[name='customer.address.city']").fill("Kochi")
        page.locator("input[name='customer.address.state']").fill("Kerala")
        page.locator("input[name='customer.address.zipCode']").fill("682024")
        page.locator("input[name='customer.phoneNumber']").fill("9876543210")
        page.locator("input[name='customer.ssn']").fill("123456789")
        page.locator("input[name='customer.username']").fill(USERNAME)
        page.locator("input[name='customer.password']").fill(PASSWORD)
        page.locator("input[name='repeatedPassword']").fill(PASSWORD)
        print("Customer details entered.")
        print("Submit registration")
        register_button = page.get_by_role("button",name="Register")
        if register_button.count() > 0:
            register_button.click()
        else:
            page.locator("input[value='Register']").click()
        page.wait_for_load_state("domcontentloaded",timeout=30000)
        page.wait_for_timeout(2000)
        print("Registration response URL:", page.url)
        print("Verify registration successful")
        page_text = page.locator("body").inner_text()
        print("Page text preview:")
        print(page_text[:1500])
        assert ("Your account was created successfully" in page_text or "Welcome" in page_text), ("Registration success message was not found.")
        print("Registration successful.")
        print("Verify user is logged in")
        expect( page.get_by_role("link", name="Accounts Overview")).to_be_visible(timeout=15000)
        expect(page.get_by_role("link",name="Log Out")).to_be_visible(timeout=15000)
        print("User is logged in.")
        print("Navigate to Accounts Overview")
        accounts_link = page.get_by_role("link", name="Accounts Overview")
        accounts_link.click()
        page.wait_for_load_state("domcontentloaded",timeout=30000)
        page.wait_for_timeout(1500)
        print("Accounts Overview URL:", page.url)
        print("Verify account is displayed")
        expect(page.locator("body")).to_contain_text("Accounts Overview",timeout=15000)
        account_links = page.locator("table#accountTable tbody tr td a")
        account_count = account_links.count()
        print("Accounts displayed:",account_count)
        assert account_count >= 1, ("No bank account was displayed.")
        print("At least one account is displayed.")
        print("Logout")
        logout_link = page.get_by_role("link",name="Log Out")
        expect(logout_link).to_be_visible(timeout=15000)
        logout_link.click()
        page.wait_for_load_state("domcontentloaded",timeout=30000)
        page.wait_for_timeout(1000)
        print("Logout URL:", page.url)
        print("Verify logout")
        expect(page.get_by_role("link",name="Register")).to_be_visible(timeout=15000)
        print("User successfully logged out.")
        print()
        print("========================================")
        print()
        print("TEST PASSED")
        print("User registered successfully.")
        print("User logged in successfully.")
        print("Account was displayed.")
        print("User logged out successfully.")
        print("========================================")
        browser.close()