#Scenario 2: Open New Account & Verify Account
from playwright.sync_api import sync_playwright, expect
PARABANK_URL = "https://parabank.parasoft.com/parabank/index.htm"
USERNAME = "testuser_987654"
PASSWORD = "Test@12345"

def test_parabank_open_new_account():
    with sync_playwright() as p:
        browser = p.chromium.launch(headless=False)
        page = browser.new_page(viewport={"width": 1440,"height": 900} )
        print("Open ParaBank")
        page.goto(PARABANK_URL,wait_until="domcontentloaded",timeout=30000)
        print("URL:", page.url)
        expect(page.locator("body")).to_contain_text("ParaBank",timeout=15000)
        print("Login")
        username_field = page.locator("input[name='username']")
        password_field = page.locator("input[name='password']")
        expect(username_field).to_be_visible(timeout=15000)
        username_field.fill(USERNAME)
        password_field.fill(PASSWORD)
        login_button = page.locator("input[value='Log In']")
        expect(login_button).to_be_visible(timeout=15000)
        login_button.click()
        page.wait_for_load_state("domcontentloaded",timeout=30000)
        page.wait_for_timeout(1500)
        print("Login URL:", page.url)
        expect(page.get_by_role("link",name="Accounts Overview")).to_be_visible(timeout=15000)
        print("Login successful.")
        print("Open New Account")
        open_account_link = page.get_by_role("link",name="Open New Account")
        expect(open_account_link).to_be_visible(timeout=15000)
        open_account_link.click()
        page.wait_for_load_state("domcontentloaded",timeout=30000)
        page.wait_for_timeout(1000)
        print("Open New Account URL:",page.url)
        expect(page.locator("body")).to_contain_text("Open New Account",timeout=15000)
        print("Select account type")
        account_type = page.locator("select#type")
        expect(account_type).to_be_visible(timeout=15000)
        account_type.select_option(label="SAVINGS")
        print("Account type selected: SAVINGS")
        print("Select existing account")
        from_account = page.locator("select#fromAccountId")
        expect(from_account).to_be_visible(timeout=15000)
        options = from_account.locator("option")
        option_count = options.count()
        print("Existing accounts available:",option_count)
        assert option_count > 0, ("No existing account is available ""to create the new account.")
        existing_account = options.first
        existing_account_value = (existing_account.get_attribute("value"))
        existing_account_text = (existing_account.inner_text().strip())
        print("Existing account selected:",existing_account_text)
        assert existing_account_value, ("Existing account does not have a value.")
        from_account.select_option(value=existing_account_value)
        print("Create new account")
        open_button = page.locator("input[value='Open New Account']")
        expect(open_button).to_be_visible(timeout=15000)
        open_button.click()
        page.wait_for_load_state("domcontentloaded",timeout=30000)
        page.wait_for_timeout(1500)
        print("New account response URL:",page.url)
        print("Verify new account creation")
        page_text = page.locator("body").inner_text()
        print("Page text preview:")
        print(page_text[:2000])
        expect(page.locator("body")).to_contain_text("Account Opened!",timeout=15000)
        print("New account created successfully.")
        print("Capture new account number")
        new_account_link = page.locator("#newAccountId")
        expect(new_account_link).to_be_visible(timeout=15000)
        new_account_number = (new_account_link.inner_text().strip())
        print("New Account Number:",new_account_number)
        assert new_account_number, ("New account number was not generated.")
        assert new_account_number.isdigit(), (f"Invalid account number: "f"{new_account_number}")
        print("Navigate to Accounts Overview")
        accounts_overview = page.get_by_role("link",name="Accounts Overview")
        expect(accounts_overview).to_be_visible(timeout=15000)
        accounts_overview.click()
        page.wait_for_load_state("domcontentloaded",timeout=30000)
        page.wait_for_timeout(1000)
        print("Accounts Overview URL:", page.url)
        expect(page.locator("body")).to_contain_text("Accounts Overview",timeout=15000)
        print("Verify new account in overview")
        account_locator = page.get_by_text(new_account_number,exact=True)
        expect(account_locator).to_be_visible(timeout=15000)
        print("New account is displayed in Accounts Overview.")
        print()
        print("==============================================")
        print("TEST PASSED")
        print("==============================================")
        print("Login successful")
        print("Open New Account page accessed")
        print("Account type: SAVINGS")
        print("Source Account:",existing_account_text)
        print("New Account Number:",new_account_number)
        print("New account successfully created")
        print("New account displayed in Accounts Overview")
        print("==============================================")
        browser.close()